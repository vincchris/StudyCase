# Challenge: Shopping Total
# Calculate the total cost of all purchased items.

# Example:
# Pencil Price = 2500
# Book Price = 5000

# Pencil Qty = 3
# Book Qty = 2

# Output:
# 17500

PencilPrice = 2500
BookPrice = 5000
PencilQty = 3
BookQty = 2

